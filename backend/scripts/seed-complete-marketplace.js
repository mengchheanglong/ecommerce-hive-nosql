async function seed() {
  const maxRetries = 25;
  let client;

  for (let attempt = 1; attempt <= maxRetries; attempt++) {
    try {
      client = new MongoClient(MONGODB_URI, { serverSelectionTimeoutMS: 2000 });
      await client.connect();
      console.log("Connected to MongoDB at:", MONGODB_URI);
      break;
    } catch (err) {
      if (attempt === maxRetries) {
        console.error(`Could not connect to MongoDB after ${maxRetries} attempts:`, err);
        process.exit(1);
      }
      console.log(`Waiting for MongoDB (${attempt}/${maxRetries})...`);
      await new Promise((r) => setTimeout(r, 1500));
    }
  }

  try {
    const dbsToSeed = ["ecommerce", "khmercart"];

    for (const dbName of dbsToSeed) {
      const db = client.db(dbName);
      console.log(`\nSeeding database "${dbName}"...`);

      // 1. Seed Products
      const prodCollection = db.collection("products");
      for (const prod of PRODUCTS) {
        await prodCollection.updateOne(
          { product_id: prod.product_id },
          { $set: { ...prod, updated_at: new Date() } },
          { upsert: true }
        );
      }
      const totalProds = await prodCollection.countDocuments();
      console.log(`- Database "${dbName}" now has ${totalProds} products.`);

      // 2. Seed Customers
      const custCollection = db.collection("customers");
      for (const cust of CUSTOMERS) {
        await custCollection.updateOne(
          { _id: cust._id },
          { $set: { ...cust, updated_at: new Date() } },
          { upsert: true }
        );
      }
      const totalCusts = await custCollection.countDocuments();
      console.log(`- Database "${dbName}" now has ${totalCusts} customers.`);

      // 3. Seed Orders
      const orderCollection = db.collection("orders");
      for (const ord of ORDERS) {
        await orderCollection.updateOne(
          { order_id: ord.order_id },
          { $set: { ...ord, updated_at: new Date() } },
          { upsert: true }
        );
      }
      const totalOrders = await orderCollection.countDocuments();
      console.log(`- Database "${dbName}" now has ${totalOrders} orders.`);
    }

    console.log("\nAll marketplace databases successfully seeded with products, customers, and orders!");
  } catch (err) {
    console.error("Seeding failed:", err);
    process.exit(1);
  } finally {
    if (client) await client.close();
  }
}

seed();
